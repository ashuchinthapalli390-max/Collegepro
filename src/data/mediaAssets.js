/**
 * Registry Query Helpers
 */
export function getMediaAssets() {
  return MEDIA_ASSETS.filter(item => item.isActive && item.isVerified);
}

export function getMediaByType(type = 'IMAGE') {
  return getMediaAssets().filter(item => item.mediaType === type);
}

export function getMediaByCategory(category = 'ALL', type = null) {
  let list = getMediaAssets();
  if (type) {
    list = list.filter(item => item.mediaType === type);
  }
  if (category && category !== 'ALL' && category !== 'All') {
    list = list.filter(item => item.category === category || item.subCategory === category);
  }
  return list;
}

export function getMediaAssetById(id) {
  return MEDIA_ASSETS.find(item => item.id === id) || null;
}
